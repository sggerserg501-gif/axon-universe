window.AtlasScenes = window.AtlasScenes || {};

window.AtlasScenes['3'] = ({ ctx, R, cx, cy, scale, t, stage, stColor }) => {
  const pulse = 1 + Math.sin(t * 4.5) * 0.12;
  const flow = (t * 0.7) % 1;

  // Полупрозрачный контур основания мозга для анатомического ориентира
  R.sphere(ctx, -0.75, 0.25, 0.25, 1.35, '#94a3b8', false, cx, cy, scale, 0.14);
  R.sphere(ctx, 0.75, 0.25, 0.25, 1.35, '#94a3b8', false, cx, cy, scale, 0.14);
  R.sphere(ctx, 0, -0.85, -0.95, 0.75, '#64748b', false, cx, cy, scale, 0.16);

  // Позвоночные артерии -> Базилярная артерия
  R.tube(ctx, [[-0.42, -1.75, -1.35], [-0.15, -1.15, -1.05], [0, -0.75, -0.85]], 0.11, '#b91c1c', cx, cy, scale);
  R.tube(ctx, [[0.42, -1.75, -1.35], [0.15, -1.15, -1.05], [0, -0.75, -0.85]], 0.11, '#b91c1c', cx, cy, scale);
  R.tube(ctx, [[0, -0.75, -0.85], [0, -0.25, -0.55], [0, 0.05, -0.35]], 0.15, '#dc2626', cx, cy, scale);

  // Задние мозговые (ЗМА) и задние соединительные артерии
  R.tube(ctx, [[0, 0.05, -0.35], [-0.65, 0.12, -0.55], [-1.45, 0.18, -0.95]], 0.1, '#ef4444', cx, cy, scale);
  R.tube(ctx, [[0, 0.05, -0.35], [0.65, 0.12, -0.55], [1.45, 0.18, -0.95]], 0.1, '#ef4444', cx, cy, scale);
  R.tube(ctx, [[-0.55, 0.1, -0.45], [-0.72, 0.22, 0.15]], 0.08, '#f87171', cx, cy, scale);
  R.tube(ctx, [[0.55, 0.1, -0.45], [0.72, 0.22, 0.15]], 0.08, '#f87171', cx, cy, scale);

  // Внутренние сонные, передние мозговые (ПМА) и передняя соединительная
  R.tube(ctx, [[-0.72, -0.55, 0.25], [-0.72, 0.22, 0.15], [-0.32, 0.35, 0.85], [-0.18, 0.48, 1.55]], 0.11, '#ef4444', cx, cy, scale);
  R.tube(ctx, [[0.72, -0.55, 0.25], [0.72, 0.22, 0.15], [0.32, 0.35, 0.85], [0.18, 0.48, 1.55]], 0.11, '#ef4444', cx, cy, scale);
  R.tube(ctx, [[-0.32, 0.35, 0.85], [0, 0.38, 0.92], [0.32, 0.35, 0.85]], 0.09, '#fca5a5', cx, cy, scale);

  // Средние мозговые артерии (СМА) с ветвлением в височные доли
  R.tube(ctx, [[-0.72, 0.22, 0.15], [-1.45, 0.38, 0.25], [-2.15, 0.62, 0.1]], 0.12, '#dc2626', cx, cy, scale);
  R.tube(ctx, [[-1.45, 0.38, 0.25], [-1.95, 0.15, 0.45]], 0.08, '#ef4444', cx, cy, scale);
  R.tube(ctx, [[0.72, 0.22, 0.15], [1.45, 0.38, 0.25], [2.15, 0.62, 0.1]], 0.12, '#dc2626', cx, cy, scale);
  R.tube(ctx, [[1.45, 0.38, 0.25], [1.95, 0.15, 0.45]], 0.08, '#ef4444', cx, cy, scale);

  // Пульсирующая волна кровотока и очаг аневризмы / стеноза
  R.sphere(ctx, 0, -0.75 + flow * 0.8, -0.85 + flow * 0.5, 0.11, '#fca5a5', true, cx, cy, scale);
  if (stage > 0) R.sphere(ctx, 0.72, 0.26, 0.22, (stage === 1 ? 0.24 : 0.45) * pulse, stColor, true, cx, cy, scale);
};
